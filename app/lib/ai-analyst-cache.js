// توحيد شكل الأمر عشان "حلل CIB" و"حلل  cib" و"حلل CIB " يتطابقوا كأمر واحد.
// بنوحّد المسافات وبنكبّر الحروف اللاتينية بس (رموز الأسهم) — العربي ما بيتأثرش بالحالة.
export function normalizeCommand(command) {
    return command
        .trim()
        .replace(/\s+/g, ' ')
        .replace(/[a-zA-Z]+/g, s => s.toUpperCase());
}
